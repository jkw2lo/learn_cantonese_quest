/* Regenerate the SIMPLIFIED block at the foot of js/data.js from Unihan.

   The cross-reference was hand-written first, and hand-written variant
   mappings are wrong in both directions: seven of the forty claims in the
   first draft were — five characters given a "simplified form" identical to
   themselves, 嚟 given 来 (which simplifies 來, a different character), and 閒
   given 闲 where Unihan says otherwise. None of that is knowable by eye.

   Only mappings inside the Basic Multilingual Plane are kept. Unihan's
   simplified form for 瞓 is an extension-B character almost no font on a
   phone can draw, and a cross-reference nobody can see is worse than none.

   Run:  node tools/fetch-simplified.mjs
   Needs tools/.unihan-variants.txt, fetched on demand.
*/

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';

const here = p => fileURLToPath(new URL(p, import.meta.url));
const CACHE = here('.unihan-variants.txt');

if (!existsSync(CACHE)) {
  process.stdout.write('fetching Unihan variants… ');
  const r = await fetch('https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip');
  if (!r.ok) { console.error('could not fetch it — check your connection'); process.exit(2); }
  const { execFileSync } = await import('child_process');
  const { tmpdir } = await import('os');
  const { join } = await import('path');
  const zip = join(tmpdir(), 'unihan.zip');
  writeFileSync(zip, Buffer.from(await r.arrayBuffer()));
  execFileSync('unzip', ['-o', '-q', zip, 'Unihan_Variants.txt', '-d', tmpdir()]);
  const all = readFileSync(join(tmpdir(), 'Unihan_Variants.txt'), 'utf8');
  writeFileSync(CACHE, all.split('\n').filter(l => l.includes('kSimplifiedVariant')).join('\n'));
  console.log('cached');
}

const cp = t => String.fromCodePoint(parseInt(t.replace(/<.*/, '').slice(2), 16));
const simp = {};
for (const line of readFileSync(CACHE, 'utf8').split('\n')) {
  if (!line.startsWith('U+')) continue;
  const [code, field, ...rest] = line.split('\t');
  if (field !== 'kSimplifiedVariant') continue;
  const ch = cp(code);
  const forms = rest.join(' ').trim().split(/\s+/).map(cp)
    .filter(v => v !== ch && v.codePointAt(0) <= 0xFFFF);    /* BMP only — see above */
  if (forms.length) simp[ch] = forms[0];
}

const file = here('../js/data.js');
const src = readFileSync(file, 'utf8');
const { HQ } = new Function(src + '\nreturn {HQ};')();

const pairs = HQ.filter(ch => simp[ch.c]).map(ch => `"${ch.c}":"${simp[ch.c]}"`);
const block = `/* ---------- simplified cross-reference ----------
   Generated by tools/fetch-simplified.mjs from Unihan's kSimplifiedVariant.
   Do not hand-edit: every hand-written version of this has been wrong.
   ${pairs.length} of ${HQ.length} characters are written differently in simplified script. */
const SIMPLIFIED = {${pairs.join(',')}};
`;

const marked = /\/\* ---------- simplified cross-reference ----------[\s\S]*?\nconst SIMPLIFIED = \{[^}]*\};\n/;
const out = marked.test(src) ? src.replace(marked, block) : src + '\n' + block;
writeFileSync(file, out);
console.log(`${pairs.length} of ${HQ.length} characters differ in simplified script`);
